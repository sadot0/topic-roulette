import { Piazzolla, Commissioner } from 'next/font/google';

/**
 * Шрифты грузятся next/font: файлы скачиваются при сборке и
 * раздаются с нашего домена — в рантайме ни одного обращения
 * к Google, ноль CLS.
 *
 * Прежняя пара Literata + Onest заменена по конкретной причине,
 * а не ради вкуса: в раздаваемых файлах не оказалось U+02BB (ʻ)
 * и U+02BC (ʼ). Это модификаторы, из которых состоят узбекские
 * oʻ и gʻ — то есть половина слов в узбекской версии добирала
 * их системным фоллбэком, другим шрифтом. Проверено по сборке:
 * из 54 правил @font-face ни одно не покрывало этот диапазон.
 *
 * У Piazzolla и Commissioner U+02BB–02BC лежат в сабсете latin,
 * поэтому subsets ['latin','cyrillic'] закрывает и русский,
 * и узбекскую латиницу целиком.
 */

/**
 * Piazzolla — книжная антиква с переменной осью opsz (8–30):
 * настоящий оптический размер, а не масштабированный рисунок.
 * На крупном кегле контраст штриха раскрывается, на мелком
 * буквы полнеют и не рассыпаются.
 *
 * Ей же набираются цифры таймера: у Piazzolla работает tnum
 * (все десять цифр шириной 560), а у интерфейсного гротеска
 * этой фичи нет вовсе — цифры прыгали бы на каждой секунде.
 */
export const display = Piazzolla({
  subsets: ['latin', 'cyrillic'],
  weight: ['400', '500', '600'],
  style: ['normal', 'italic'],
  display: 'swap',
  variable: '--font-display',
});

/**
 * Commissioner — гротеск с осью FLAR (flare, 0–100): расширение
 * штриха у окончаний. Небольшое значение снимает механическую
 * сухость, не превращая букву в засечную. Именно оно даёт
 * мягкость, которой добивались скруглениями.
 */
export const ui = Commissioner({
  subsets: ['latin', 'cyrillic'],
  weight: ['400', '500', '600'],
  display: 'swap',
  variable: '--font-ui',
});
